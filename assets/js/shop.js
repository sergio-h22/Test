/* Resolve the "@ink" / "@accent" placeholders against the chosen garment
   colour. Storing tokens rather than literal hex is what lets one design serve
   both a black shirt and a white one without a second copy of the artwork. */
function shopDesignFor(designId, garmentColor) {
  const found = SHOP_DESIGNS.filter(function (d) { return d.id === designId; })[0];
  if (!found) return null;
  const ink = SHOP_DARK_GARMENTS.indexOf(garmentColor) > -1 ? SHOP_INK.onDark : SHOP_INK.onLight;
  const resolve = function (layers) {
    return (layers || []).map(function (l) {
      const copy = JSON.parse(JSON.stringify(l));
      if (copy.fill === "@ink") copy.fill = ink;
      else if (copy.fill === "@accent") copy.fill = SHOP_INK.accent;
      return copy;
    });
  };
  return { front: resolve(found.design.front), back: resolve(found.design.back) };
}

function shopDesign(id) {
  return SHOP_DESIGNS.filter(function (d) { return d.id === id; })[0] || null;
}

/* Designs that can be printed on a given product, used to cross-link from a
   product page back into the shop. */
function shopDesignsForProduct(productId) {
  return SHOP_DESIGNS.filter(function (d) { return d.garments.indexOf(productId) > -1; });
}

/* ---------------------------------------------------------------- previews */

/* A shop grid shows eight designs at once. Spinning up eight Fabric canvases
   to do that would pull the whole editor runtime onto a browsing page and pay
   for a raster surface per card. The garment art is already SVG and the design
   layers are already vector, so the preview is emitted as plain SVG markup
   instead: no canvas, no editor dependency, sharp at any size, and it renders
   before the customizer script has even been requested.
   The editor still owns editing. This owns looking. */

const SHOP_CANVAS = { w: 600, h: 620 };

function shopEscXML(s) {
  return String(s).replace(/[&<>"']/g, function (c) {
    return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" }[c];
  });
}

/* Layers store position and size as fractions of the print area, which is what
   lets the same design sit correctly on a tee and a hoodie without a second
   set of coordinates. Converting back to canvas units is this one function. */
function shopLayerSVG(layer, area) {
  const cx = area.x + layer.x * area.w;
  const cy = area.y + layer.y * area.h;
  const w  = (layer.w || 0) * area.w;

  if (layer.type === "shape") {
    const h = (layer.h || 0) * area.h;
    const rot = layer.angle ? ' transform="rotate(' + layer.angle + ' ' + cx + ' ' + cy + ')"' : "";
    const op  = layer.opacity != null ? ' opacity="' + layer.opacity + '"' : "";
    if (layer.shape === "circle") {
      return '<ellipse cx="' + cx + '" cy="' + cy + '" rx="' + (w / 2) + '" ry="' + (h / 2) +
             '" fill="' + shopEscXML(layer.fill) + '"' + op + rot + "/>";
    }
    /* rect and line are the same primitive at different heights. */
    return '<rect x="' + (cx - w / 2) + '" y="' + (cy - h / 2) + '" width="' + w + '" height="' + h +
           '" fill="' + shopEscXML(layer.fill) + '"' + op + rot + "/>";
  }

  if (layer.type === "text") {
    const chars = Math.max(String(layer.text).length, 1);
    /* Approximate the natural size from the box, then let textLength do the
       exact fitting. Without textLength the preview drifts whenever a webfont
       loads late or falls back, which is the one thing a preview must not do. */
    const size = Math.min(area.h * 0.42, (w / chars) * 1.85);
    const rot = layer.angle ? ' transform="rotate(' + layer.angle + ' ' + cx + ' ' + cy + ')"' : "";
    const weight = layer.bold ? ' font-weight="700"' : "";
    const spacing = layer.spacing ? ' letter-spacing="' + (layer.spacing / 1000 * size) + '"' : "";
    return '<text x="' + cx + '" y="' + cy + '" font-family="' + shopEscXML(layer.font) + '"' +
           ' font-size="' + size + '"' + weight + spacing +
           ' fill="' + shopEscXML(layer.fill) + '" text-anchor="middle" dominant-baseline="central"' +
           ' textLength="' + w + '" lengthAdjust="spacingAndGlyphs"' + rot + ">" +
           shopEscXML(layer.text) + "</text>";
  }
  return "";
}

/* Full preview: garment silhouette plus the resolved design, as one SVG.
   Callers must have run ensureGarmentDefs() so the <symbol> set exists, and
   must call applyGarmentColor() on the wrapping element to tint the cloth. */
/* The single renderer both the homepage strip and the shop page draw
 * designs with. It replaces two earlier near-duplicates (one in each
 * caller) and the id-lookup version this file used to export, which
 * stopped being called once both pages started reading through
 * CatalogService and is deleted here rather than left to rot.
 *
 * A design that carries a real photo for a side (design.assets.front /
 * .back, set by the admin tool once Supabase is connected) shows that
 * photo. Everything else falls back to drawing the design's vector layers
 * onto the garment SVG, which is how the 18 hand-built designs render
 * today and will keep working exactly as before. Both paths return markup
 * sized by the same CSS classes, so a caller does not need to know which
 * one it got.
 */
function shopRenderPreview(design, productId, garmentColor, side, svgClass, photoClass) {
  const product = (typeof PRODUCTS !== "undefined")
    ? PRODUCTS.filter(function (p) { return p.id === productId; })[0] : null;
  if (!product || !product.art) return "";

  const useSide = side || "front";
  const label = design.name + " on a " + product.name.toLowerCase().replace(/s$/, "") +
    ", " + String(garmentColor).toLowerCase();

  /* Photos and vector art size differently: a photo needs object-fit to avoid
     distorting to a box drawn for a 600x620 viewBox, so callers pass a
     separate class for each rather than one class trying to serve both. */
  const photo = design.assets && design.assets[useSide];
  if (photo) {
    return '<img class="' + (photoClass || svgClass) + '" src="' + shopEscXML(photo) + '" alt="' + shopEscXML(label) +
           '" loading="lazy" decoding="async">';
  }

  const art = (typeof CatalogService !== "undefined")
    ? CatalogService.resolveArtwork(design, garmentColor)
    : { front: [], back: [] };
  const layers = art[useSide] || [];
  const area = (typeof printAreaFor === "function")
    ? printAreaFor(productId, useSide)
    : { x: 218, y: 196, w: 164, h: 216 };

  return '<svg class="' + svgClass + '" viewBox="0 0 ' + SHOP_CANVAS.w + " " + SHOP_CANVAS.h + '" ' +
         'role="img" aria-label="' + shopEscXML(label) + '">' +
         '<use href="#garment-' + shopEscXML(product.art[useSide]) + '"/>' +
         layers.map(function (l) { return shopLayerSVG(l, area); }).join("") +
         "</svg>";
}
