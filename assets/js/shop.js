/* Ready-made shirt designs.
 *
 * These are the "buy it as-is" side of the shop, as opposed to templates.js,
 * which seeds the customizer with a starting point the customer then edits.
 * The two files look similar on purpose: a shop design is a template that
 * happens to be finished, so both speak the same layer vocabulary and both
 * render through the same engine.
 *
 * Everything here is text and shapes, no bitmaps. That is a deliberate
 * constraint rather than a shortcut: a design defined as data recolours per
 * garment, scales to any print size without resampling, prints as clean
 * vector separations, and costs nothing to ship over the wire. It also means
 * the preview the customer sees is generated by the same code that will drive
 * the print file, so the preview cannot drift away from the product.
 *
 * price is null on every entry, matching products.js. No prices have been
 * supplied for this shop yet and inventing them would put fictional numbers in
 * front of paying customers. The UI renders a visible placeholder instead.
 */

